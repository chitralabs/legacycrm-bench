def find_cases():
    cases = []
    for cj in sorted(CASES_ROOT.glob("*/*/case.json")):
        cases.append(cj.parent)
    return cases


def generate_all(out_root: Path):
    attempted, skipped = [], []
    for case_dir in find_cases():
        meta = json.loads((case_dir / "case.json").read_text())
        spec_text = (case_dir / "target_spec.md").read_text()
        deliverables = meta["deliverables"]
        produced = None
        for gen in GENERATORS:
            produced = gen(case_dir, spec_text, deliverables)
            if produced is not None:
                break
        if produced is None or set(produced) != set(deliverables):
            skipped.append(meta["id"])
            continue
        dest = out_root / meta["id"]
        dest.mkdir(parents=True, exist_ok=True)
        for fname, content in produced.items():
            (dest / fname).write_text(content)
        attempted.append((meta["id"], case_dir, dest))
    return attempted, skipped


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out-root", required=True, help="directory for generated candidate solutions")
    ap.add_argument("--no-eval", action="store_true", help="generate only; skip sandboxed evaluation")
    args = ap.parse_args()
    out_root = Path(args.out_root).resolve()
    out_root.mkdir(parents=True, exist_ok=True)

    attempted, skipped = generate_all(out_root)
    print("C5 rule-based transpiler: generated %d candidates, skipped %d cases"
          % (len(attempted), len(skipped)))
    print("Skipped (bespoke interface, not mechanically derivable): %s"
          % (", ".join(skipped) if skipped else "none"))
    if args.no_eval:
        return

    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from sandbox import run_sandboxed  # noqa: E402

    results = []
    for case_id, case_dir, sol_dir in attempted:
        res = run_sandboxed(case_dir, sol_dir)
        results.append(res)
        print("  %-7s %2d/%2d passed  all_passed=%s" %
              (case_id, res["num_passed"], res["num_tests_collected"], res["all_passed"]))

    meta_line = {"run_type": "c5_transpiler",
                 "timestamp_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                 "cases_attempted": len(attempted),
                 "cases_skipped": len(skipped),
                 "skipped_ids": skipped}
    RESULTS_PATH.parent.mkdir(parents=True, exist_ok=True)
    with RESULTS_PATH.open("w") as f:
        f.write(json.dumps({"_meta": meta_line}) + "\n")
        for res in results:
            f.write(json.dumps(res) + "\n")

    print("\n%-8s %-10s %-6s %8s %10s" % ("case", "category", "diff", "passed", "all_passed"))
    for res in results:
        print("%-8s %-10s %-6s %5d/%-3d %10s" %
              (res["case_id"], res["category"], res["difficulty"],
               res["num_passed"], res["num_tests_collected"], res["all_passed"]))
    n_all = sum(1 for r in results if r["all_passed"])
    print("\nAttempted: %d  all-pass: %d  skipped: %d (%s)"
          % (len(results), n_all, len(skipped), ", ".join(skipped)))
    print("Results written to %s" % RESULTS_PATH)


if __name__ == "__main__":
    main()
