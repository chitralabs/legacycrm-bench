def gen_audit_cfg(case_dir, spec_text, deliverables):
    cfg = case_dir / "legacy" / "audit_config.cfg"
    if not cfg.is_file() or deliverables != ["migrated.py"]:
        return None
    if not lift_signature(spec_text, "audited_columns"):
        return None
    return {"migrated.py": GENERATED_HEADER + AUDIT_PARSER_SRC}


