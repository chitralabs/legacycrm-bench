    for line in cfg_text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        tokens = line.split()
        if len(tokens) == 3 and tokens[0] == "AUDIT":
            out.setdefault(tokens[1], set()).add(tokens[2])
    return out
