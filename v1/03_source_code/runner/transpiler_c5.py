#!/usr/bin/env python3
"""Condition C5: deterministic rule-based transpiler baseline (Protocol Amendment AD-02).

A no-LLM, no-network control that measures how much of LegacyCRM-Bench is mechanically
saturable from the legacy artifacts alone. For each case it can handle, it generates the
case's deliverable files under <out-root>/<CASE_ID>/ using ONLY:

  * the case's legacy/ artifacts (parsed genuinely: VRL rule files, workflow XML,
    INI/CFG/CSV configuration), and
  * generic, family-level generation rules (one generator per artifact/interface family).

Honesty constraints (enforced by construction):
  * No per-case hard-coded expected values; no reading of reference/, tests/, or
    GROUND_TRUTH.md. The only non-legacy input is target_spec.md, read exclusively to
    lift the required interface (deliverable file names and function signatures) —
    legitimate, since real migrations are given their target interface.
  * A case whose bespoke interface cannot be produced mechanically is SKIPPED
    (no output emitted); skips are recorded as data in the results _meta line.

Generators implemented (artifact family -> deliverable):
  vrl_validate    legacy/*.vrl              -> migrated.py  (VAL-family validate())
  workflow_engine legacy/<workflow>.xml     -> migrated.py  (WFL-family fire())
  batch_schedule  legacy/batch_jobs.cfg     -> migrated.py + schedule.json (BAT-01 family)
  endpoints_json  legacy/endpoints.ini      -> endpoints.json (INT-01 family)
  enums_json      legacy/data_dictionary.csv-> enums.json  (CFG-01 family)
  workflows_json  legacy/workflows.xml      -> workflows.json (CFG-03 family)
  audit_cfg       legacy/audit_config.cfg   -> migrated.py  (AUD-01 family)

Usage:
  python transpiler_c5.py --out-root <dir> [--no-eval]

Results are written to 05_results/c5_transpiler_baseline.jsonl (a _meta header line,
then one line per attempted case), via the sandboxed evaluator (runner/sandbox.py).
Stdlib only; deterministic.
"""
