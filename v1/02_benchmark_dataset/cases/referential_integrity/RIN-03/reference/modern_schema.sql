-- RIN-03 reference schema: Meridian CRM tables with declared referential integrity.
-- Legacy soft delete is retired; deletion authority is the FK graph.
-- Apply with PRAGMA foreign_keys=ON on the connection.

CREATE TABLE ACCT_MASTER (
  ACCT_ID     TEXT PRIMARY KEY,
  ACCT_NM     TEXT NOT NULL,
  ACCT_TYP    TEXT,
  REGION_CD   TEXT,
  ANN_REV     NUMERIC,
  CURR_CD     TEXT,
  CRED_LIMIT  NUMERIC,
  CRED_HOLD   TEXT,
  CREATE_DT   TEXT
);

CREATE TABLE CONT_MASTER (
  CONT_ID     TEXT PRIMARY KEY,
  ACCT_ID     TEXT NOT NULL,
  FRST_NM     TEXT,
  LAST_NM     TEXT NOT NULL,
  EMAIL_TX    TEXT,
  PREF_CH     TEXT,
  OPTOUT_FLG  TEXT,
  FOREIGN KEY (ACCT_ID) REFERENCES ACCT_MASTER(ACCT_ID) ON DELETE RESTRICT
);

CREATE TABLE ORD_HEADER (
  ORD_ID      TEXT PRIMARY KEY,
  ACCT_ID     TEXT NOT NULL,
  ORD_DT      TEXT,
  STAT_CD     TEXT,
  DISC_PCT    NUMERIC,
  TOT_AMT     NUMERIC,
  FOREIGN KEY (ACCT_ID) REFERENCES ACCT_MASTER(ACCT_ID) ON DELETE RESTRICT
);

CREATE TABLE ORD_LINE (
  ORD_ID      TEXT NOT NULL,
  LINE_NO     INTEGER NOT NULL,
  PROD_ID     TEXT,
  QTY         NUMERIC,
  UNIT_PRC    NUMERIC,
  EXT_AMT     NUMERIC,
  PRIMARY KEY (ORD_ID, LINE_NO),
  FOREIGN KEY (ORD_ID) REFERENCES ORD_HEADER(ORD_ID) ON DELETE CASCADE
);
